'use strict';

/**
 * Общая шина событий панели.
 *
 * Через неё сервисы сообщают интерфейсу о том, что происходит прямо сейчас:
 *   'job'     — прогресс длительной операции (установка сервера, загрузка модов);
 *   'status'  — изменение состояния процесса сервера;
 *   'servers' — изменился список серверов (создан/удалён/переименован).
 *
 * Шина намеренно не зависит ни от чего — её можно подключать из любого модуля.
 */

const { EventEmitter } = require('events');

const bus = new EventEmitter();
bus.setMaxListeners(0);

module.exports = bus;
